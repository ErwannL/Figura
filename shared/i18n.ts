export type Locale = 'en' | 'fr';

export function translate(
  locale: Locale,
  key: I18nKey,
  params: Record<string, string | number> = {},
): string {
  const dict = locale === 'fr' ? fr : en;
  return dict[key].replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}
